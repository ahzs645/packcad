describe("MailerBox Newton fold golden", () => {
  it("keeps final vertex positions stable after the triangulation migration", () => {
    const project = createMailerBoxProject();
    if (!project.foldModel) throw new Error("MailerBox fixture did not produce a fold model");

    const result = foldNewtonSequence(project.foldModel);
    expect(result.maxEdgeError).toBeLessThan(1e-6);
    expect(result.maxAngleErrorDeg).toBeLessThan(1e-4);
    expect(result.positions.length).toBe(GOLDEN_POSITIONS.length);
    result.positions.forEach((position, vertexIndex) => {
      position.forEach((coordinate, axis) => {
        expect
          .soft(Math.abs(coordinate - GOLDEN_POSITIONS[vertexIndex][axis]))
          .toBeLessThan(1e-3);
      });
    });
  });
});
